-- التاريخ: 2026-10-25
--
-- الهدف:
--   تعيين أدوار (creator, input_reviewer, final_reviewer) للمستخدمين
--   في نظام تبليغات هيئة التدريس
--
-- ملاحظة هامة:
--   هذا الملف أمثلة فقط. يجب تعديل أسماء المستخدمين الفعلية
--   قبل التشغيل في بيئة الإنتاج.
--
-- الأدوار:
--   • creator          - منشئ التبليغ (يمكنه إنشاء تبليغات جديدة)
--   • input_reviewer   - مدخل البيرول (يراجع ويُكمل مرحلة الإدخال)
--   • final_reviewer   - مراجع البيرول (يُكمل المراجعة النهائية)
--
-- طريقة التشغيل:
--   Supabase Dashboard → SQL Editor → New query → الصق الملف كاملاً → Run.
-- ============================================================================

-- ============================================================================
-- تعيين الأدوار للمستخدمين الفعليين
-- ============================================================================

-- تعيين منشئ التبليغ
UPDATE public.users
SET faculty_notification_role = 'creator'
WHERE username = 'horia';

-- تعيين مدخل البيرول
UPDATE public.users
SET faculty_notification_role = 'input_reviewer'
WHERE username = 'hanaa';

-- تعيين مراجع البيرول
UPDATE public.users
SET faculty_notification_role = 'final_reviewer'
WHERE username = 'gehad';

-- ============================================================================
-- عرض المستخدمين الحاليين وأدوارهم
-- ============================================================================

-- استعلام لعرض جميع المستخدمين وأدوارهم الحالية
SELECT 
  id,
  username,
  full_name,
  faculty_notification_role,
  permissions,
  created_at
FROM public.users
ORDER BY created_at;

